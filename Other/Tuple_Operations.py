#Tuple Operations 

print(" ---Tuple Operations--- ")

T1=(10,20,30,40)
T2=(50,60,70,80)

print("T[0]:",T1[0])
print("T[-1]:",T1[-1])
print("T1[1:3]:",T1[1:3])
print("T1+T2:",T1+T2)
print("T1*2:",T1*2)
print(20 in T1)
print("length of T2 tuple:",len(T2))
print("Max of T1:",max(T1))
print("Min of T2:",min(T2))
print("Sum of T1:",sum(T1))
      
